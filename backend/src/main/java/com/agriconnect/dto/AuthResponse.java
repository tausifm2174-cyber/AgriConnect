package com.agriconnect.dto;

import com.agriconnect.entity.Role;
import com.agriconnect.entity.UserStatus;

/**
 * Authentication response returned upon successful login or registration.
 * Never exposes passwords or password hashes.
 */
public class AuthResponse {

    private String token;
    private String tokenType = "Bearer";
    private Integer userId;
    private String fullName;
    private String email;
    private String phone;
    private Role role;
    private UserStatus status;
    private String message;

    public AuthResponse() {
    }

    public AuthResponse(String token, Integer userId, String fullName, String email, String phone, Role role, UserStatus status, String message) {
        this.token = token;
        this.tokenType = "Bearer";
        this.userId = userId;
        this.fullName = fullName;
        this.email = email;
        this.phone = phone;
        this.role = role;
        this.status = status;
        this.message = message;
    }

    public String getToken() {
        return token;
    }

    public void setToken(String token) {
        this.token = token;
    }

    public String getTokenType() {
        return tokenType;
    }

    public void setTokenType(String tokenType) {
        this.tokenType = tokenType;
    }

    public Integer getUserId() {
        return userId;
    }

    public void setUserId(Integer userId) {
        this.userId = userId;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public Role getRole() {
        return role;
    }

    public void setRole(Role role) {
        this.role = role;
    }

    public UserStatus getStatus() {
        return status;
    }

    public void setStatus(UserStatus status) {
        this.status = status;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }
}
